CREATE OR REPLACE TRIGGER NEW_ORDER_NOTIFICATION
AFTER UPDATE ON FOODORDER
FOR EACH ROW
DECLARE
  V NUMBER;
  C NUMBER;
  R NUMBER;
BEGIN
  SELECT USER_ID INTO C FROM CUSTOMER WHERE CUSTOMER_ID = :NEW.CUSTOMER_ID;
  SELECT USER_ID INTO R FROM RESTAURANT WHERE RESTAURANT_ID = :NEW.RESTAURANT_ID;
  IF :NEW.STATUS = 'I' THEN
    V := NOTIFICATION_ID_SEQ.NEXTVAL;
    INSERT INTO NOTIFICATION VALUES (V, C, SYSDATE, 'U', 'O', 'Your order is on the way');
    INSERT INTO ORDER_NOTIFICATION VALUES (V, :NEW.ORDER_ID);
  ELSIF :NEW.STATUS = 'O' THEN
    V := NOTIFICATION_ID_SEQ.NEXTVAL;
    INSERT INTO NOTIFICATION VALUES (V, R, SYSDATE, 'U', 'O', 'A customer ordered a menu');
    INSERT INTO ORDER_NOTIFICATION VALUES (V, :NEW.ORDER_ID);
  END IF;
END;
/
