CREATE OR REPLACE TRIGGER REACT_NOTIFICATION
AFTER INSERT ON REACTS
FOR EACH ROW
DECLARE
  V NUMBER;
  C NUMBER;
BEGIN
  SELECT COUNT(*) INTO C FROM POST_NOTIFICATION WHERE POST_ID = :NEW.POST_ID;
  IF C = 0 THEN
    V := NOTIFICATION_ID_SEQ.NEXTVAL;
    INSERT INTO NOTIFICATION VALUES (
      V,
      (SELECT USER_ID FROM POSTS WHERE POST_ID = :NEW.POST_ID),
      SYSDATE,
      'U',
      'P',
      (SELECT NAME FROM USERS WHERE USER_ID = :NEW.USER_ID) || ' and ' || (SELECT REACT_COUNT FROM POSTS WHERE POST_ID = :NEW.POST_ID) || ' other has reacted to your post'
    );
    INSERT INTO POST_NOTIFICATION VALUES (V, :NEW.POST_ID);
  ELSE
    SELECT NOTIFICATION_ID INTO V FROM POST_NOTIFICATION WHERE POST_ID = :NEW.POST_ID;
    UPDATE NOTIFICATION
      SET TIME = SYSDATE,
          STATUS = 'U',
          MESSAGE = (SELECT NAME FROM USERS WHERE USER_ID = :NEW.USER_ID) || ' and ' || (SELECT REACT_COUNT FROM POSTS WHERE POST_ID = :NEW.POST_ID) || ' other has reacted to your post'
      WHERE NOTIFICATION_ID = V;
  END IF;
END;
/

