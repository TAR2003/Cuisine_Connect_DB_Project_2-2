CREATE OR REPLACE FUNCTION GET_CUSTOMER(U NUMBER) RETURN NUMBER IS
  ID NUMBER;
BEGIN
  SELECT CUSTOMER_ID INTO ID FROM CUSTOMER WHERE USER_ID = U;
  RETURN ID;
END;
/

CREATE OR REPLACE FUNCTION GET_RESTAURANT(U NUMBER) RETURN NUMBER IS
  ID NUMBER;
BEGIN
  SELECT RESTAURANT_ID INTO ID FROM RESTAURANT WHERE USER_ID = U;
  RETURN ID;
END;
/

CREATE OR REPLACE FUNCTION GET_PAGE(U NUMBER) RETURN NUMBER IS
  ID NUMBER;
BEGIN
  SELECT PAGE_ID INTO ID FROM FOODIE_PAGE WHERE USER_ID = U;
  RETURN ID;
END;
/

CREATE OR REPLACE FUNCTION DELETE_POST(P_POST_ID NUMBER) RETURN NUMBER IS
  V_USER NUMBER;
BEGIN
  BEGIN
    SELECT USER_ID INTO V_USER FROM POSTS WHERE POST_ID = P_POST_ID;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN 0;
  END;
  INSERT INTO ADMIN_LOG VALUES (ACTIVITY_ID_SEQ.NEXTVAL, 'DELETING POST', SYSDATE, V_USER, 'Function: DELETE_POST', NULL);
  DELETE FROM POSTS WHERE POST_ID IN (SELECT POST_ID FROM SHARE_POST WHERE ORIGIN_ID = P_POST_ID);
  DELETE FROM POSTS WHERE POST_ID = P_POST_ID;
  RETURN 1;
END;
/

CREATE OR REPLACE PROCEDURE DELETE_LATE_RESERVATIONS IS
BEGIN
  DELETE FROM RESERVATIONS WHERE TIME < SYSDATE;
END;
/

CREATE OR REPLACE PROCEDURE COUNT_TRANSACTION_FOR_ALL(ANSWER OUT NUMBER) IS
