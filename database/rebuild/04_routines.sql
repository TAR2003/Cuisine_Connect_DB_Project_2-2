CREATE OR REPLACE PROCEDURE COUNT_TRANSACTION(UID IN NUMBER, ANSWER OUT NUMBER) IS
BEGIN
  SELECT SUM(TOTALPRICE) INTO ANSWER FROM FOODORDER
  WHERE RESTAURANT_ID = (SELECT RESTAURANT_ID FROM RESTAURANT WHERE USER_ID = UID);
END;
/

CREATE OR REPLACE PROCEDURE COUNT_MENU_TRANSACTION(UID IN NUMBER, ANSWER OUT NUMBER) IS
BEGIN
  SELECT SUM(PRICE) INTO ANSWER FROM MENU
  WHERE RESTAURANT_ID = (SELECT RESTAURANT_ID FROM RESTAURANT WHERE USER_ID = UID);
END;
/

